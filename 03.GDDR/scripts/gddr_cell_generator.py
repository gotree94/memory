from typing import List, Dict
from pathlib import Path
from enum import Enum


class SignallingType(Enum):
    """시그널링 타입"""
    NRZ = "nrz"            # 2-Level (GDDR5/GDDR6)
    PAM4 = "pam4"          # 4-Level (GDDR6X)
    PAM3 = "pam3"          # 3-Level (연구)


class ChannelType(Enum):
    """채널 구조 타입"""
    SINGLE_32BIT = "single_32bit"      # 단일 32-bit (GDDR5)
    DUAL_16BIT = "dual_16bit"          # 듀얼 16-bit 서브채널 (GDDR6)
    DUAL_16BIT_PAM4 = "dual_16bit_pam4" # 듀얼 + PAM4 (GDDR6X)


@dataclass
class TechnologyNode:
    """기술 노드 정의"""
    name: str
    node_nm: int
    gate_length: float  # nm
    min_pitch: float    # nm
    vdd: float          # V (core)
    vddq: float         # V (I/O 전원)
    vth: float          # V
    oxide_thickness: float  # nm


@dataclass
class GDDRConfig:
    """GDDR 세대 설계 파라미터"""
    generation: str
    tech_node: TechnologyNode
    signalling: SignallingType
    channel_type: ChannelType
    # I/O 파라미터
    data_rate_per_pin: float    # Gbps
    eye_margin: float           # mV (아이 다이어그램 마진)
    tx_swing: float             # V (출력 스윙)
    # 채널 파라미터
    bus_width: int              # 비트
    channels: int               # 독립 채널 수
    subchannels: List[int]      # 서브채널 구성
    # 대역폭
    bandwidth: float            # GB/s
    # 셀 어레이
    num_banks: int
    bank_groups: int
    # 패키징
    package: str
    pins: int
    # 특징
    features: List[str] = field(default_factory=list)


